use std::cell::RefCell;
use std::io;
use std::path::Path;

/// Shared input/work limits for one synchronous collection on the current thread.
///
/// Byte limits count source bytes, not Rust heap allocations or RSS. Entry and
/// line/path limits also bound parser/container expansion. Output buffers and
/// retained snapshot generations require separate limits in the caller.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[cfg_attr(feature = "serde1", derive(serde::Serialize, serde::Deserialize))]
pub struct CollectionLimits {
    /// Maximum admitted source bytes across all files, including failed reads.
    /// EOF/oversize probes may read one extra byte per file; probes are not retained.
    pub input_bytes: usize,
    /// Maximum bytes in any one text or binary source.
    pub file_bytes: usize,
    /// Maximum bytes in one text line, excluding its newline.
    pub line_bytes: usize,
    /// Total directory entries visited across all collectors.
    pub entries: usize,
    /// Total requested source files, including failed metadata/open attempts.
    pub files: usize,
    /// Maximum source path length in bytes.
    pub path_bytes: usize,
    /// Maximum visible cgroup ancestors; excess visibility is reported incomplete.
    pub ancestors: usize,
}

impl Default for CollectionLimits {
    fn default() -> Self {
        Self {
            input_bytes: 16 * 1024 * 1024,
            file_bytes: 4 * 1024 * 1024,
            line_bytes: 64 * 1024,
            entries: 65_536,
            files: 65_536,
            path_bytes: 4096,
            ancestors: 64,
        }
    }
}

impl CollectionLimits {
    /// Reject zero limits and inconsistent per-file/line limits before I/O.
    pub fn validate(&self) -> io::Result<()> {
        if self.input_bytes == 0
            || self.file_bytes == 0
            || self.line_bytes == 0
            || self.entries == 0
            || self.files == 0
            || self.path_bytes == 0
            || self.ancestors == 0
            || self.file_bytes > self.input_bytes
            || self.line_bytes > self.file_bytes
        {
            return Err(io::Error::new(io::ErrorKind::InvalidInput, "invalid memory collection limits"));
        }
        Ok(())
    }
}

/// First resource limit encountered; a snapshot carrying it is incomplete.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[cfg_attr(feature = "serde1", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde1", serde(rename_all = "snake_case"))]
pub enum CollectionLimit {
    /// Aggregate source bytes.
    InputBytes,
    /// A source exceeded its per-file allowance.
    FileBytes,
    /// A text line exceeded its allowance.
    LineBytes,
    /// Aggregate directory entries.
    Entries,
    /// Aggregate source attempts, including missing/denied sources.
    Files,
    /// A source path exceeded its allowance.
    PathBytes,
    /// Cgroup ancestor visibility exceeded its allowance.
    Ancestors,
    /// Instrumented retained allocation allowance.
    RetainedHeap,
    /// Instrumented temporary allocation allowance.
    ScratchHeap,
}

/// Bounded collection accounting; `limit_exceeded` explicitly marks partial data.
///
/// Generated by WORA's [`collect_with_limits`] accounting on the collecting
/// thread, not read from a kernel memory file. Counts describe admitted input
/// and work, rather than allocated heap capacity or RSS.
#[derive(Clone, Copy, Default, Debug, Eq, PartialEq)]
#[cfg_attr(feature = "serde1", derive(serde::Serialize, serde::Deserialize))]
pub struct CollectionReport {
    /// Admitted source bytes; never exceeds the aggregate allowance.
    pub input_bytes: usize,
    /// Admitted directory entries; never exceeds the aggregate allowance.
    pub entries: usize,
    /// Admitted source attempts, including unsuccessful lookups.
    pub files: usize,
    /// First exhausted limit, if any. Individual source errors remain separate.
    pub limit_exceeded: Option<CollectionLimit>,
}

struct State {
    limits: CollectionLimits,
    report: CollectionReport,
}
thread_local! { static ACTIVE: RefCell<Option<State>> = const { RefCell::new(None) }; }

struct Reset;
impl Drop for Reset {
    fn drop(&mut self) {
        ACTIVE.with(|active| *active.borrow_mut() = None);
    }
}

/// Run a synchronous collector with one shared budget for all its subcollectors.
///
/// The budget is scoped to this thread and restored even when the closure
/// unwinds. Nested scopes are rejected. Do not move collection to another thread
/// inside the closure. Standalone parsers of caller-owned strings are outside
/// this I/O budget. Any exceeded limit marks the returned report incomplete.
pub fn collect_with_limits<T>(limits: CollectionLimits, collect: impl FnOnce() -> T) -> io::Result<(T, CollectionReport)> {
    limits.validate()?;
    ACTIVE.with(|active| {
        let mut active = active.borrow_mut();
        if active.is_some() {
            return Err(io::Error::other("nested memory collection budget"));
        }
        *active = Some(State {
            limits,
            report: CollectionReport::default(),
        });
        Ok(())
    })?;
    let _reset = Reset;
    let result = crate::heap::with_default_budget(collect);
    let report = ACTIVE.with(|active| active.borrow().as_ref().map(|state| state.report).unwrap_or_default());
    Ok((result, report))
}

pub(crate) fn limits() -> CollectionLimits {
    ACTIVE.with(|active| active.borrow().as_ref().map(|state| state.limits).unwrap_or_default())
}

pub(crate) fn file_limit(requested: usize) -> usize {
    ACTIVE.with(|active| active.borrow().as_ref().map(|s| requested.min(s.limits.file_bytes)).unwrap_or(requested))
}

pub(crate) fn exceeded(limit: CollectionLimit) -> io::Error {
    mark_exceeded(limit);
    io::Error::other(format!("memory collection limit exceeded: {limit:?}"))
}

pub(crate) fn mark_exceeded(limit: CollectionLimit) {
    ACTIVE.with(|active| {
        if let Some(state) = active.borrow_mut().as_mut() {
            state.report.limit_exceeded.get_or_insert(limit);
        }
    });
}

pub(crate) fn charge_bytes(bytes: usize) -> io::Result<()> {
    let admitted = ACTIVE.with(|active| {
        let mut active = active.borrow_mut();
        let Some(state) = active.as_mut() else { return true };
        if bytes > state.limits.input_bytes.saturating_sub(state.report.input_bytes) {
            state.report.input_bytes = state.limits.input_bytes;
            return false;
        }
        state.report.input_bytes += bytes;
        true
    });
    if admitted { Ok(()) } else { Err(exceeded(CollectionLimit::InputBytes)) }
}

pub(crate) fn remaining_bytes() -> usize {
    ACTIVE.with(|active| {
        active
            .borrow()
            .as_ref()
            .map(|s| s.limits.input_bytes - s.report.input_bytes)
            .unwrap_or(usize::MAX)
    })
}

pub(crate) fn charge_entry() -> io::Result<()> {
    let admitted = ACTIVE.with(|active| {
        let mut active = active.borrow_mut();
        let Some(state) = active.as_mut() else { return true };
        if state.report.entries >= state.limits.entries {
            return false;
        }
        state.report.entries += 1;
        true
    });
    if admitted { Ok(()) } else { Err(exceeded(CollectionLimit::Entries)) }
}

pub(crate) fn charge_file() -> io::Result<()> {
    let admitted = ACTIVE.with(|active| {
        let mut active = active.borrow_mut();
        let Some(state) = active.as_mut() else { return true };
        if state.report.files >= state.limits.files {
            return false;
        }
        state.report.files += 1;
        true
    });
    if admitted { Ok(()) } else { Err(exceeded(CollectionLimit::Files)) }
}

pub(crate) fn file_available() -> bool {
    ACTIVE.with(|active| active.borrow().as_ref().is_none_or(|state| state.report.files < state.limits.files))
}

pub(crate) fn check_path(path: &Path) -> io::Result<()> {
    if path.as_os_str().len() > limits().path_bytes {
        return Err(exceeded(CollectionLimit::PathBytes));
    }
    Ok(())
}
